class TestTBRStructuralInvariants:
    """TBR neighbours are normalised to strict binary trees via
    ``_normalise_binary``; leaf set is preserved."""

    @pytest.mark.parametrize("n", [4, 5, 6, 7, 8])
    def test_all_tbr_neighbours_are_binary(self, n: int):
        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)
        neighbours = _tbr_only_search()._generate_neighbors(tree)
        for nb in neighbours:
            assert _is_binary(nb), (
                f"TBR neighbour is not strictly binary: {nb.to_newick(branch_lengths=False)}"
            )

    @pytest.mark.parametrize("n", [5, 7, 8, 9])
    def test_tbr_neighbourhood_is_larger_than_nni(self, n: int):
        """A TBR neighbourhood equal to the NNI one means TBR did nothing.

        TBR is a strictly more powerful move than NNI -- NNI is a TBR with the
        cut one level up -- so wherever a TBR neighbourhood is larger, every
        one of those extra topologies is one the search could not have reached
        before.

        This is the only property that detects the walk-direction bug in
        ``TBROperation``. That bug walked DOWN from ``reconnect_node1`` looking
        for ``cut_node1``, which lies below it, so the walk always fell off the
        tree and raised ValueError -- which ``_generate_neighbors`` swallows.
        The neighbours it still produced were all perfectly valid: binary, right
        leaf set, symmetric, no duplicates. Every other test in this file
        passed with the bug restored.

        What it produced was a TBR neighbourhood *identical in size to the NNI
        one* at every n: 4/4, 4/4, 8/8, 10/10, 12/12 for n = 5..9. The search
        was silently running NNI twice. With the walk direction corrected the
        counts are 6, 4, 16, 20, 34 -- strictly larger than NNI wherever a
        larger neighbourhood is reachable at all.

        n = 6 is excluded because the two coincide there even when the code is
        correct; 4 is excluded because both are empty for want of an internal
        edge.
        """
        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)
        nni_count = len(_nni_only_search()._generate_neighbors(tree))
        tbr_count = len(_tbr_only_search()._generate_neighbors(tree))
        assert tbr_count > nni_count, (
            f"n={n}: TBR reached {tbr_count} topologies, the same as the "
            f"NNI-only neighbourhood ({nni_count}) -- the TBR operator "
            f"contributed nothing, which is the signature of the "
            f"walk-direction bug"
        )

    @pytest.mark.parametrize("n", [4, 5, 6, 7, 8])
    def test_all_tbr_neighbours_have_same_leaf_set(self, n: int):
        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)
        neighbours = _tbr_only_search()._generate_neighbors(tree)
        for nb in neighbours:
            assert set(nb.leaf_names) == set(labels), (
                f"TBR neighbour dropped/added taxa: in={set(labels)} out={set(nb.leaf_names)}"
            )

    @pytest.mark.parametrize("n", [4, 5, 6, 7, 8])
    def test_no_tbr_neighbour_equals_input(self, n: int):
        """TBR is a genuine rearrangement: input must not be in its own
        TBR neighbourhood (the implementation only retains distinct Newicks
        in the dedup step)."""
        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)
        orig_newick = tree.to_newick()
        neighbours = _tbr_only_search()._generate_neighbors(tree)
        for nb in neighbours:
            assert nb.to_newick() != orig_newick, (
                f"TBR returned the input tree unchanged; n = {n}"
            )


class TestTBRSymmetry:
    """If B is reachable from A by TBR in the production code, then A is
    reachable from B.

    This is *exactly* testable: for every TBR neighbour B of A, ask whether
    A (by its unrooted-splits signature) appears among B's TBR neighbours.
    A relation that is symmetric on the production-code's subset of TBR is
    the strongest evidence that the operator's reconnect logic is actually
    invertible -- a non-symmetric TBR would indicate the cut/reconnect
    bookkeeping has a hidden one-way bias.
    """

    @pytest.mark.parametrize("n", [5, 6, 7])
    def test_tbr_is_symmetric(self, n: int):
        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)

        tbr_neighbors = _tbr_only_search(seed=42)._generate_neighbors(tree)
        assert tbr_neighbors, "TBR neighbourhood was empty for n >= 5"

        orig_splits = R.unrooted_splits(tree)
        # For every TBR-reachable B, build B's own TBR neighbourhood and
        # check that A (by unrooted splits) is among them.
        violations = 0
        for nb in tbr_neighbors:
            back = _tbr_only_search(seed=42)._generate_neighbors(nb)
            back_splits = {R.unrooted_splits(t) for t in back}
            if orig_splits not in back_splits:
                violations += 1
        assert violations == 0, (
            f"TBR symmetry violated for n = {n}: {violations} of "
            f"{len(tbr_neighbors)} neighbours did not reach back"
        )


class TestNNIisSubsetOfTBR:
    """Every NNI move (by unrooted topology) is also reachable via the
    production code's TBR.

    NNI is a special case of TBR (the second cut is taken at the parent of
    ``cut_node1``).  Therefore for every topology reachable by NNI there must
    exist a TBR sequence producing it.  We verify the *production code's*
    TBR generator still reaches every NNI topology.
    """

    @pytest.mark.parametrize("n", [5, 6, 7])
    def test_nni_topologies_in_tbr_neighbourhood(self, n: int):
        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)

        nni_neighbors = _nni_only_search(seed=42)._generate_neighbors(tree)
        tbr_neighbors = _tbr_only_search(seed=42)._generate_neighbors(tree)

        nni_splits = {R.unrooted_splits(t) for t in nni_neighbors}
        tbr_splits = {R.unrooted_splits(t) for t in tbr_neighbors}

        # NNI includes "self" topologies for the root edge (the swap that
        # re-roots to the same unrooted tree); discard self-splits before
        # checking the subset relation.
        nni_new = nni_splits - {R.unrooted_splits(tree)}
        missing = nni_new - tbr_splits
        assert not missing, (
            f"NNI topologies missing from TBR for n = {n}: {missing}"
        )


