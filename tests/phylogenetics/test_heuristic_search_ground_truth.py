def _binary_tree(labels, seed: int = 42) -> PhyloTree:
    """Build a random binary tree over ``labels`` with a fixed numpy seed."""
    rng = np.random.default_rng(seed)
    return R.random_binary_tree(list(labels), rng)


def _is_binary(tree: PhyloTree) -> bool:
    """Return True iff every node has arity 0 or 2 (strictly binary)."""
    if tree.root is None:
        return True
    return all(node.arity in (0, 2) for node in tree.root.get_all_nodes())


def _nni_only_search(seed: int = 42) -> HeuristicSearch:
    """An ``HeuristicSearch`` whose neighbourhood is NNI-only.

    ``nni_swap_probability=1.0`` makes ``tbr_prob=0``, and the in-loop
    test ``self._rng.random() >= self._tbr_prob`` is then always true,
    so TBR is never generated.
    """
    return HeuristicSearch(nni_swap_probability=1.0, random_seed=seed)


def _tbr_only_search(seed: int = 42) -> HeuristicSearch:
    """An ``HeuristicSearch`` whose neighbourhood includes TBR (always tried)."""
    return HeuristicSearch(nni_swap_probability=0.0, random_seed=seed)


def _uniform_sequences(labels) -> dict[str, str]:
    """Build same-length sequences where each taxon has its own state set."""
    return {name: name * 2 for name in labels}


def _divergent_sequences(labels) -> dict[str, str]:
    """Build sequences with structure that gives a non-trivial parsimony score."""
    # Alternating blocks so Fitch has to walk both sides at every site.
    seqs = {
        "A": "ACGTACGT",
        "B": "TTTTAAAA",
        "C": "AAAACCCC",
        "D": "CCCCGGGG",
        "E": "GGGGAAAA",
        "F": "TTTTCCCC",
        "G": "ACGTACGT",
        "H": "TTTTCCCC",
    }
    return {name: seqs[name] for name in labels}


