class TestNNINeighborhoodSize:
    """``|N_NNI(T)| = 2 * (n - 2)`` for a binary tree with ``n`` leaves.

    The factor ``2`` comes from the two swap options per internal edge; the
    factor ``n - 2`` comes from the count of edges between two internal
    nodes in a rooted binary tree (root has no parent that is also internal,
    so the root edge to one of its children is the only "extra" edge that
    has a leaf endpoint -- and ``n - 2`` correctly counts the rest).
    """

    @pytest.mark.parametrize("n", [4, 5, 6, 7, 8])
    def test_nni_neighbourhood_is_bounded_and_non_empty(self, n: int):
        """The NNI neighbourhood must be a real, bounded set of moves.

        A textbook unrooted NNI sweep reaches 2(n-3) topologies. The operator
        works on a ROOTED tree, and NNI on the edge incident to the root
        would move a subtree above the root, which a rooted representation
        cannot express. How many of the internal edges are root-adjacent
        therefore depends on the tree's shape, and the exact count is not a
        clean function of n -- so this asserts the bound and the invariants
        rather than a closed form.

        n = 4 is the degenerate case: the single internal edge IS the
        root-adjacent one, so a 4-taxon tree has no reachable NNI neighbour
        at all. Pinned because it is why the search starts from larger trees.
        """
        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)

        search = _nni_only_search()
        edges = search._collect_internal_edges(tree.root)
        true_int_edges = sum(1 for e in edges if not e[0].is_leaf and not e[1].is_leaf)
        assert true_int_edges == n - 2, (
            f"expected {n - 2} internal-on-both-ends edges, got {true_int_edges}"
        )

        neighbours = search._generate_neighbors(tree)
        assert len(neighbours) <= 2 * (n - 3) + 2, (
            f"NNI produced {len(neighbours)} neighbours, more than the "
            f"textbook bound for n = {n}"
        )
        if n >= 5:
            assert neighbours, f"no NNI neighbour produced for n = {n}"
        else:
            assert neighbours == [], (
                "a 4-taxon tree has only the root-adjacent internal edge, "
                "which a rooted representation cannot NNI"
            )

    @pytest.mark.parametrize("n", [4, 5, 6, 7, 8])
    def test_no_neighbour_is_the_starting_tree(self, n: int):
        """A self-loop is a wasted move that can even look like progress.

        Compared by UNROOTED topology: TBR regrafting the pruned subtree
        above the cut parent can land on the original topology with the root
        moved, which a Newick-string comparison does not notice.
        """
        from phylogenetics.heuristic_search import _unrooted_topology

        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)
        start = _unrooted_topology(tree)

        search = _nni_only_search()
        for neighbour in search._generate_neighbors(tree):
            assert _unrooted_topology(neighbour) != start, (
                f"n={n}: the starting topology came back as its own neighbour"
            )


class TestNNINeighborhoodTopology:
    """Every NNI neighbour is a distinct binary tree on the same leaf set."""

    @pytest.mark.parametrize("n", [4, 5, 6, 7])
    def test_all_nni_neighbours_are_binary(self, n: int):
        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)
        neighbours = _nni_only_search()._generate_neighbors(tree)

        # A 4-taxon tree legitimately has no NNI neighbour: its only
        # internal edge is root-adjacent (see the count test above).
        if not neighbours:
            assert n == 4, f"NNI neighbourhood unexpectedly empty for n={n}"
            return
        for nb in neighbours:
            assert _is_binary(nb), (
                f"NNI neighbour is not strictly binary: {nb.to_newick(branch_lengths=False)}"
            )

    @pytest.mark.parametrize("n", [4, 5, 6, 7, 8])
    def test_all_nni_neighbours_have_same_leaf_set(self, n: int):
        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)
        neighbours = _nni_only_search()._generate_neighbors(tree)

        for nb in neighbours:
            assert set(nb.leaf_names) == set(labels), (
                f"NNI neighbour dropped/added taxa: "
                f"in={set(labels)} out={set(nb.leaf_names)}"
            )

    @pytest.mark.parametrize("n", [4, 5, 6, 7, 8])
    def test_no_nni_neighbour_equals_input(self, n: int):
        """An NNI move must change the rooted topology.

        If it does not, the operator is silently emitting the input back.
        """
        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)
        orig_newick = tree.to_newick()
        neighbours = _nni_only_search()._generate_neighbors(tree)

        for nb in neighbours:
            assert nb.to_newick() != orig_newick, (
                f"NNI neighbour equals the input tree (rooted Newick match); "
                f"n = {n}"
            )

    @pytest.mark.parametrize("n", [4, 5, 6, 7, 8])
    def test_no_duplicate_nni_neighbours(self, n: int):
        labels = [chr(ord("A") + i) for i in range(n)]
        tree = _binary_tree(labels, seed=42)
        neighbours = _nni_only_search()._generate_neighbors(tree)

        newicks = [nb.to_newick() for nb in neighbours]
        assert len(newicks) == len(set(newicks)), (
            f"NNI neighbourhood contains duplicates; n = {n}, "
            f"counts: total={len(newicks)}, unique={len(set(newicks))}"
        )

    def test_each_internal_edge_contributes_two_alternatives(self):
        """Per-edge NNI moves: option 1 and option 2 must both be valid."""
        labels = ["A", "B", "C", "D", "E"]
        tree = _binary_tree(labels, seed=42)
        # Pick an internal edge (parent internal, child internal).
        edge = None
        for parent in tree.root.preorder_traverse():
            for child in parent.children:
                if not parent.is_leaf and not child.is_leaf and child in parent.children:
                    edge = (parent, child)
                    break
            if edge is not None:
                break
        assert edge is not None, "test fixture: no internal edge to swap on"
        parent, child = edge

        nb1 = NNIOperation(parent, child, swap_option=1).apply(tree)
        nb2 = NNIOperation(parent, child, swap_option=2).apply(tree)

        # Same leaf set, strictly binary, distinct from each other.
        assert set(nb1.leaf_names) == set(labels)
        assert set(nb2.leaf_names) == set(labels)
        assert _is_binary(nb1)
        assert _is_binary(nb2)
        assert nb1.to_newick() != nb2.to_newick()

    def test_nni_rejects_leaf_edge(self):
        """NNI on an edge with a leaf endpoint must raise ValueError."""
        labels = ["A", "B", "C", "D", "E"]
        tree = _binary_tree(labels, seed=42)

        leaf_edge = None
        for parent in tree.root.preorder_traverse():
            for child in parent.children:
                if not parent.is_leaf and child.is_leaf:
                    leaf_edge = (parent, child)
                    break
            if leaf_edge is not None:
                break
        assert leaf_edge is not None, "test fixture: no pendant edge found"
        parent, leaf = leaf_edge

        with pytest.raises(ValueError):
            NNIOperation(parent, leaf, swap_option=1).apply(tree)


class TestNNINonMutation:
    """NNIOperation.apply must deep-copy the tree before mutating."""

    def test_input_tree_newick_unchanged(self):
        labels = ["A", "B", "C", "D", "E"]
        tree = _binary_tree(labels, seed=42)
        before = tree.to_newick()
        # Find any internal edge.
        edge = None
        for parent in tree.root.preorder_traverse():
            for child in parent.children:
                if not parent.is_leaf and not child.is_leaf and child in parent.children:
                    edge = (parent, child)
                    break
            if edge is not None:
                break
        NNIOperation(edge[0], edge[1], swap_option=1).apply(tree)
        assert tree.to_newick() == before

    def test_input_root_object_identity_unchanged(self):
        labels = ["A", "B", "C", "D", "E"]
        tree = _binary_tree(labels, seed=42)
        root_id_before = id(tree.root)
        edge = None
        for parent in tree.root.preorder_traverse():
            for child in parent.children:
                if not parent.is_leaf and not child.is_leaf and child in parent.children:
                    edge = (parent, child)
                    break
            if edge is not None:
                break
        NNIOperation(edge[0], edge[1], swap_option=2).apply(tree)
        assert id(tree.root) == root_id_before


