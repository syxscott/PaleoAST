# =============================================================================
# _collect_internal_edges -- what it actually returns
# =============================================================================
#
# NOTE: the production code's ``_collect_internal_edges`` returns *every*
# edge incident to an internal node, including pendant edges from an internal
# node to a leaf.  The function name is therefore misleading: the set is
# "edges incident to internal nodes", not "edges between two internal nodes".
# The downstream operators (NNI, TBR) cope correctly by filtering/rejecting
# pendant edges -- but the function's contract should be documented and
# ideally fixed.  We pin the actual behaviour here so a future "fix" that
# tightens the filter is observed.


class TestCollectInternalEdges:
    def test_includes_only_edges_with_internal_parent(self):
        labels = ["A", "B", "C", "D", "E"]
        tree = _binary_tree(labels, seed=42)
        s = HeuristicSearch(random_seed=42)
        edges = s._collect_internal_edges(tree.root)
        # Every collected edge has the parent endpoint non-leaf.
        for parent, _child in edges:
            assert not parent.is_leaf, (
                f"edge has a leaf parent: parent={parent.name}"
            )


