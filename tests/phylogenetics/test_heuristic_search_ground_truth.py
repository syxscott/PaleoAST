"""
================================================================================
Ground-truth tests for ``phylogenetics/heuristic_search.py``
================================================================================

Why this file exists
--------------------
``heuristic_search.py`` carries only **16.1% line coverage**, and most of the
uncovered code is algorithmic: NNI/TBR neighbourhood operators and a heuristic
search loop on top of Fitch parsimony.  The shape of that code is exactly the
shape where a silent bug hides, because a wrong neighbourhood is *still* a
neighbourhood: the operator returns a tree, the search runs to completion,
Fitch scores it, the run prints a score.  Nothing crashes.

This module pins the algorithms down against closed-form properties so that
silent defects (wrong neighbour count, lost topologies, input mutation, lost
reproducibility, dropped taxa) become loud.

Properties we test
------------------
**NNI neighbourhood size -- closed form**
    A binary rooted tree with ``n`` leaves has ``n-1`` internal nodes.
    Of those, ``n-2`` are non-root and have a parent that is itself internal,
    giving exactly ``n-2`` edges between two internal nodes.  Each such edge
    has exactly **2 NNI alternatives** (swap ``sib`` with ``b1``, swap ``sib``
    with ``b2``).  So for any binary tree the NNI neighbourhood generated by
    the production code contains exactly ``2(n-2)`` distinct neighbours.

    The production code's ``_collect_internal_edges`` is *named* "internal
    edges" but in fact returns every edge incident to an internal node (so
    also pendant edges to leaves).  NNI correctly *rejects* those via
    ``if node1.is_leaf or node2.is_leaf: raise ValueError`` and the
    surrounding ``try/except`` silently drops the failures.  The closed-form
    count therefore still holds, but it relies on the leaf check rather than
    on the edge set being filtered upstream -- worth a comment in the report.

**NNI structural invariants**
    * each neighbour has the SAME leaf set as the input;
    * each neighbour is STRICTLY BINARY (every internal node has exactly 2
      children, every leaf has 0);
    * no neighbour equals the input (by rooted Newick);
    * no two neighbours are duplicates of each other;
    * applying ``NNIOperation`` does not mutate the input tree.

**TBR structural invariants**
    * each TBR neighbour has the same leaf set as the input;
    * each TBR neighbour is strictly binary (via ``_normalise_binary``);
    * the production code's restricted TBR relation is SYMMETRIC: if the
      code can reach B from A then it can reach A from B.  This is exact
      and decidable without enumerating the topology space;
    * every NNI move is also reachable by TBR (NNI is a subset operation
      of TBR, by construction -- an NNI swap on an internal edge is just a
      TBR with the cut one level above).

**HeuristicSearch invariants**
    * reproducibility: same seed -> same best tree and best score;
    * non-mutation: the input tree is not mutated (identity + Newick);
    * leaf conservation: every leaf passed in is in the result;
    * score sanity: best_score is finite and non-negative (parsimony on
      integer-state Fitch is a count).

Definitions
-----------
NNI (Robinson 1971, also described in Felsenstein 2004 ch.30): on an internal
edge (parent, child), exchange the parent's sibling with one of the child's
two non-parent children.  Two alternatives per edge.

TBR (同样出处): remove an internal edge (splits tree into A and B), pick a
second internal edge on side A (not the path back to the first cut), and
reconnect: the parent of the second cut grafts onto the second component,
the child of the second cut grafts onto the first component.

References
----------
* Robinson, D. F. (1971). Comparison of labeled trees with valency three.
  J. Combinatorial Theory, Ser. B, 11(2):105-119.
* Felsenstein, J. (2004). Inferring Phylogenies. Sinauer Associates. ch.30.
* Saitou, N. & Nei, M. (1987). The neighbor-joining method. Mol. Biol. Evol.
  4:406-425 (defines additive trees and the recovery guarantee used by
  ``reference_algorithms.random_binary_tree``).
"""

