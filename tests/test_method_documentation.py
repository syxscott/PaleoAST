"""
The method documentation cannot fall behind the code.

WHAT THIS GUARDS
~~~~~~~~~~~~~~~~
``docs/methods/`` answers the question a reader actually has: *this number
-- why should I believe it?*  Four things have to be true for it:

  1. every analysis the application offers has an entry;
  2. the per-analysis table says what evidence exists for it, and that
     table is generated from the same matrix the validation ratchet uses,
     so the two cannot disagree;
  3. the hand-written half -- the assumptions, the applicability, the
     references -- is actually there, and is not an empty shell;
  4. the generated half is current.

Why (3) is a test at all: a document that lists the analyses and says
nothing about their assumptions answers none of the reader's questions,
and it looks exactly like a document that does.

THE REFERENCES
~~~~~~~~~~~~~~
A method document that cites nothing can be checked by nobody.  Each
domain document must carry at least one reference, and the reference must
name a source that a reader can look up -- so the check is that the
document carries a "## 参考" section with actual entries, not that the
citations are correct.  Whether a citation is the right one is a matter
for a domain expert, and this test cannot settle it; what it can settle is
that the slot exists and is not empty.
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from plugins.catalog import BUILTIN_ANALYSES

DOCS = REPO / "docs" / "methods"

#: The table row format the generator writes.  The analysis name is in
#: backticks, which is also how the hand-written prose refers to it.
_ROW = re.compile(r"^\|\s*`([a-z0-9_]+)`\s*\|", re.MULTILINE)


def _documents() -> list[pathlib.Path]:
    return sorted(p for p in DOCS.glob("*.md") if p.name != "README.md")


def _documented_analyses() -> set[str]:
    found: set[str] = set()
    for path in _documents():
        found.update(_ROW.findall(path.read_text(encoding="utf-8")))
    return found


def test_every_analysis_has_a_method_entry():
    """An analysis nobody documented is an analysis nobody can trust.

    This is the same list the application offers, taken from the catalog
    the plugin registry is asserted against, so a new analyzer cannot
    appear without a document.
    """
    documented = _documented_analyses()
    missing = sorted(entry.name for entry in BUILTIN_ANALYSES if entry.name not in documented)
    assert not missing, (
        f"{len(missing)} analyses have no method documentation: {missing}. "
        "Add them to the right file under docs/methods/ and run "
        "`python scripts/method_docs.py`."
    )


def test_every_method_document_states_assumptions_and_references():
    """The hand-written half has to be there.

    A document that is only a table answers none of the reader's
    questions, and it is indistinguishable from one that does.
    """
    for path in _documents():
        text = path.read_text(encoding="utf-8")
        assert "## 参考" in text, f"{path.name} has no reference section"
        assert "假设" in text, f"{path.name} does not state its assumptions"
        # The reference section must carry entries, not just a heading.
        references = text.split("## 参考", 1)[1]
        entries = [line for line in references.splitlines() if line.strip().startswith("- ")]
        assert entries, f"{path.name} has a reference heading but no references"


def test_the_generated_tables_are_current():
    """The tables are regenerated by a script; they must not have drifted.

    The script rewrites only what is between the markers, so the hand-
    written half is safe.
    """
    script = REPO / "scripts" / "method_docs.py"
    proc = subprocess.run(
        [sys.executable, str(script), "--check"],
        cwd=REPO,
        capture_output=True,
        text=True,
        timeout=600,
    )
    assert proc.returncode == 0, (
        f"the method documents are out of date -- run `python scripts/method_docs.py`:\n{proc.stdout}\n{proc.stderr}"
    )
